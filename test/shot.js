// Headless screenshots of every view with a live simulated team.
const { app, BrowserWindow } = require('electron');
const fs = require('fs'), os = require('os'), path = require('path');
const { createServer } = require('../src/server/http');
const { setup, simulate } = require('./demo');
app.disableHardwareAcceleration();
const out = path.join(__dirname, 'shots'); fs.mkdirSync(out, { recursive: true });
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
app.whenReady().then(async () => {
  const root = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'concord-demo-')), 'nebula-shop');
  fs.mkdirSync(root);
  const c = setup(root);
  const s = createServer({ getCoordinator: () => c, staticDir: path.join(__dirname, '..', 'renderer'), port: 47400 });
  const port = await s.listen();
  process.env.CONCORD_PORT = String(port);
  const sim = simulate(c, 380);
  const win = new BrowserWindow({ width: 1440, height: 900, show: false, webPreferences: { offscreen: true, preload: path.join(__dirname, 'mock-preload.js'), contextIsolation: true, sandbox: false } });
  win.webContents.on('console-message', (e, level, msg) => { if (level >= 2) console.log('console:', msg); });
  await win.loadURL(`http://127.0.0.1:${port}/`);
  const js = (code) => win.webContents.executeJavaScript(code);
  const snap = async (name) => { fs.writeFileSync(path.join(out, name + '.png'), (await win.webContents.capturePage()).toPNG()); console.log('shot', name); };
  await js(`window.__S.thoughts = { nova: { text: 'Merging duplicate SKUs first, then clamping qty so the UI cannot send 0.', at: Date.now() }, atlas: { text: 'Rounding only in total(), per the money decision in memory.', at: Date.now() }, 'claude-code': { text: 'Coupon codes from mobile have stray spaces; trimming before lookup.', at: Date.now() }, orion: { text: 'Writing a test that two coupons cannot stack.', at: Date.now() } }`);
  await wait(9000);
  await snap('1-live');
  await js("__show('board')"); await wait(900); await snap('2-board');
  await js("__show('files')"); await wait(700); await js("__loadFile('src/cart.js')"); await wait(2200); await snap('3-files');
  await js("__show('memory')"); await wait(900); await snap('4-memory');
  await js("__show('agents')"); await wait(900); await snap('5-agents');
  await js("__profileModal(null); document.querySelector('[data-reg=china]').click(); document.querySelector('[data-p=moonshot]').click();"); await wait(700); await snap('6-connect-model');
  await js("document.getElementById('modal').classList.remove('on'); __show('connect')"); await wait(800); await snap('7-connect');
  c.checkpoints = new (require('../src/core/checkpoints').Checkpoints)(root);
  await c.checkpoint('Before the team started', { agent: 'user' }); await wait(2500); await c.checkpoint('Nova finished “Merge duplicate SKUs”', { agent: 'nova' }); await wait(2500); await c.checkpoint('Atlas finished “Round totals once”', { agent: 'atlas' });
  await js("__show('safety')"); await wait(1500); await js("document.querySelector('[data-cpv]') && document.querySelector('[data-cpv]').click()"); await wait(800); await snap('9-safety');
  await js("document.getElementById('feedbackBtn').click()"); await wait(900); await snap('10-feedback');
  await js("document.getElementById('modal').classList.remove('on'); __show('agents'); document.querySelector('#agents-wrap, .agents-wrap').scrollTop = 9999"); await wait(600);
  await js("document.documentElement.dataset.theme='light'; __show('score')"); await wait(3500); await snap('8-light');
  await js("document.documentElement.dataset.theme='dark'; __S.snap=null; __show('welcome')"); await wait(900); await snap('0-welcome');
  clearInterval(sim);
  console.log('stats', JSON.stringify(c.stats));
  app.quit();
});
